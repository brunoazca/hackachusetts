#!/usr/bin/env python3
"""Write a SAFE, repo-scoped excerpt of the Kiro Crew audit log.

The raw host log (~/.kiro/crew/audit.log) records every tool call on this
machine: other projects, absolute home paths, full tool outputs, and any
secret that ever appeared in a command. It must never be published as-is
(this repo is public). This keeps only what proves Kiro usage on THIS repo:

  * entries whose cwd / working_dir / command mention this repo
  * timestamp, event kind, tool name, stated purpose, and the command or path
  * NO tool output, home paths shortened to ~, secrets redacted:
    every .env.local value, known credential formats, and any long
    mixed letter+digit token (hex hashes and UUIDs are kept)

Usage: python3 .kiro/audit/sanitize_audit_log.py [SRC] [DEST]
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / ".kiro" / "crew" / "audit.log"
DEST = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / ".kiro" / "audit" / "audit.log"
REPO_MARK = "hackachusetts"
HOME = str(Path.home())
MAX_FIELD = 400

LINE_RX = re.compile(r"^(\S+)\s+([A-Z_]+):\s*(\{.*\})\s*$")
TOKEN_RX = re.compile(r"[A-Za-z0-9_\-]{20,}")
HEX_RX = re.compile(r"^[0-9a-fA-F\-]+$")
CRED_RX = [
    re.compile(r"\b(AKIA|ASIA)[0-9A-Z]{16}\b"),
    re.compile(r"\b(gh[pousr]_[A-Za-z0-9]{20,}|github_pat_[A-Za-z0-9_]{20,})\b"),
    re.compile(r"\bxox[abpors]-[A-Za-z0-9-]{10,}\b"),
    re.compile(r"\bsk-(ant-)?[A-Za-z0-9_-]{16,}\b"),
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----"),
]


def env_values() -> list[str]:
    p = ROOT / ".env.local"
    if not p.exists():
        return []
    out = []
    for line in p.read_text(errors="replace").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            v = line.split("=", 1)[1].strip().strip("\"'")
            if len(v) >= 8:
                out.append(v)
    return out


SECRETS = env_values()


def _token_sub(m: re.Match) -> str:
    t = m.group(0)
    if HEX_RX.match(t):
        return t  # commit SHAs, UUIDs
    if any(c.isdigit() for c in t) and any(c.isalpha() for c in t) and not re.search(r"[_\-]{1}[a-z]+[_\-]", t):
        return "[REDACTED]"
    return t


def redact(text: str) -> str:
    text = text.replace("\r", " ").replace("\n", " ⏎ ").replace(HOME, "~")
    for s in SECRETS:
        text = text.replace(s, "[REDACTED]")
    for rx in CRED_RX:
        text = rx.sub("[REDACTED]", text)
    text = TOKEN_RX.sub(_token_sub, text)
    return text[:MAX_FIELD] + ("…" if len(text) > MAX_FIELD else "")


def main() -> int:
    if not SRC.exists():
        print(f"No audit log at {SRC} — nothing to sync.")
        return 0
    kept = 0
    out = ["# Kiro Crew audit log, SANITIZED excerpt for this repo only.",
           "# Generated by .kiro/audit/sanitize_audit_log.py. Tool outputs dropped, secrets and home paths",
           "# redacted. The raw HMAC-protected log stays on each teammate's machine and is not published.",
           ""]
    for raw in SRC.read_text(errors="replace").splitlines():
        m = LINE_RX.match(raw)
        if not m or REPO_MARK not in raw.lower():
            continue
        ts, kind, body = m.groups()
        try:
            ev = json.loads(body)
        except json.JSONDecodeError:
            continue
        ti = ev.get("tool_input") or {}
        where = " ".join(str(x) for x in (ev.get("cwd"), ti.get("working_dir"), ti.get("command"), ti.get("path")) if x)
        if REPO_MARK not in where.lower():
            continue
        what = ti.get("command") or ti.get("path") or ti.get("pattern") or ""
        if not what and isinstance(ti.get("operations"), list):
            what = ", ".join(str(o.get("path", "")) for o in ti["operations"] if isinstance(o, dict))
        purpose = ti.get("__tool_use_purpose", "")
        out.append(f"{ts} {kind} {ev.get('tool_name', '?')} | {redact(purpose)} | {redact(str(what))}")
        kept += 1
    DEST.parent.mkdir(parents=True, exist_ok=True)
    DEST.write_text("\n".join(out) + "\n")
    print(f"Synced sanitized audit log: {kept} repo entries -> {DEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
